package dev.brikk.house.sql.schema.inputs

import dev.brikk.house.sql.shape.DdlCatalog
import dev.brikk.house.sql.shape.SchemaCache
import dev.brikk.house.sql.shape.ShapeCatalog
import java.io.ByteArrayOutputStream
import java.io.DataOutputStream
import java.nio.file.Files
import java.nio.file.LinkOption.NOFOLLOW_LINKS
import java.nio.file.Path
import java.nio.file.StandardCopyOption
import java.security.MessageDigest
import kotlin.io.path.createDirectories
import kotlin.io.path.readText
import org.jetbrains.amper.plugins.Input
import org.jetbrains.amper.plugins.Output
import org.jetbrains.amper.plugins.TaskAction

private const val HEADER = "// Generated by Brikk schema-inputs v1. Do not edit.\n"

/** The declared file/directory input becomes a real Kotlin compiler/IDE source input. */
@TaskAction
fun prepareSchemaInput(
    @Input schemaInput: Path,
    @Input projectFile: Path,
    compilerArgs: List<String>?,
    schemaDialect: String,
    defaultSchema: String,
    moduleName: String,
    @Output sourceDir: Path,
) {
    validateCompilerSchema(schemaInput, projectFile.toAbsolutePath().parent, compilerArgs.orEmpty(), schemaDialect, defaultSchema)
    writeSchemaRevision(schemaInput, schemaDialect, defaultSchema, moduleName, sourceDir)
}

/** Never claim to track a different schema from the one passed to the compiler. */
internal fun validateCompilerSchema(input: Path, projectRoot: Path, arguments: List<String>, dialect: String, defaultSchema: String) {
    val prefix = "plugin:dev.brikk.house.sql.compiler:"
    fun option(name: String): String? {
        val values = arguments.map { it.removePrefix("-P").trimStart('=', ' ') }
            .filter { it.startsWith("$prefix$name=") }.map { it.removePrefix("$prefix$name=") }
        require(values.size <= 1) { "Duplicate compiler schema option '$name'" }
        return values.singleOrNull()
    }
    val path = option("schema") ?: error("Schema-input tracking requires an explicit compiler schema option in freeCompilerArgs")
    val configured = Path.of(path).let { if (it.isAbsolute) it else projectRoot.resolve(it) }
    require(configured.toRealPath() == input.toRealPath()) { "Tracked schema does not match the compiler schema option" }
    if (!Files.isDirectory(input)) {
        require((option("schemaDialect") ?: "postgres") == dialect) { "Tracked DDL dialect does not match the compiler option" }
        require((option("defaultSchema") ?: "") == defaultSchema) { "Tracked DDL default schema does not match the compiler option" }
    }
}

/** Also used by explicit capture to update the private consumer's registered source root. */
fun writeSchemaRevision(
    schemaInput: Path,
    schemaDialect: String,
    defaultSchema: String,
    moduleName: String,
    sourceDir: Path,
): Boolean {
    require(Files.isRegularFile(schemaInput) || Files.isDirectory(schemaInput)) { "Schema input is not a file or directory" }
    val captured = Files.isDirectory(schemaInput)
    // SQL owns active-generation selection, validation and locking. Never scan old
    // generations ourselves or put captured object names/types into generated code.
    val catalog = if (captured) SchemaCache.load(schemaInput) else
        DdlCatalog.fromDdl(schemaInput.readText(), schemaDialect, defaultSchema.ifBlank { null })
    val revision = catalogRevision(catalog,
        if (captured) "snapshot-v1" else "ddl-v1:$schemaDialect:$defaultSchema",
        schemaInput.toRealPath().toString())
    val module = digest(moduleName.toByteArray()).take(16)
    val content = HEADER + "package dev.brikk.house.sql.generated.schema_inputs.m_$module\n\n" +
        "internal const val BRIKK_SCHEMA_REVISION: String = \"$revision\"\n"
    val file = sourceDir.resolve("BrikkSchemaInput.kt")
    require(!Files.isSymbolicLink(sourceDir.parent) && !Files.isSymbolicLink(sourceDir) && !Files.isSymbolicLink(file)) {
        "Managed schema source paths must not be symbolic links"
    }
    if (Files.exists(file, NOFOLLOW_LINKS)) {
        val previous = file.readText()
        require(previous.startsWith(HEADER)) { "Refusing to overwrite an unrecognized schema source file" }
        if (previous == content) return false
    }
    sourceDir.createDirectories()
    val temporary = Files.createTempFile(sourceDir, ".schema-input-", ".tmp")
    try {
        Files.writeString(temporary, content)
        Files.move(temporary, file, StandardCopyOption.REPLACE_EXISTING, StandardCopyOption.ATOMIC_MOVE)
    } finally { Files.deleteIfExists(temporary) }
    return true
}

/** The active typing contract, not capture timestamps, UUIDs, locks or archived generations. */
internal fun catalogRevision(catalog: ShapeCatalog, format: String, selector: String): String {
    val bytes = ByteArrayOutputStream()
    DataOutputStream(bytes).use { out ->
        fun string(value: String) {
            val encoded = value.toByteArray(Charsets.UTF_8)
            out.writeInt(encoded.size)
            out.write(encoded)
        }
        string("brikk-schema-input-v1")
        string(format)
        string(selector)
        for ((kind, shapes) in listOf("tables" to catalog.tables, "slots" to catalog.slots)) {
            string(kind)
            out.writeInt(shapes.size)
            for ((name, shape) in shapes.toSortedMap()) {
                string(name)
                out.writeInt(shape.columns.size)
                for (column in shape.columns) {
                    string(column.name)
                    string(column.type)
                    out.writeByte(when (column.nullable) { true -> 1; false -> 0; null -> 2 })
                    out.writeBoolean(column.quoted)
                }
            }
        }
    }
    return digest(bytes.toByteArray())
}

private fun digest(bytes: ByteArray): String = MessageDigest.getInstance("SHA-256").digest(bytes)
    .joinToString("") { "%02x".format(it.toInt() and 255) }
